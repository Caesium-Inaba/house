let currentLang: 'zh' | 'en' = 'zh'

export function setLang(lang: 'zh' | 'en') {
  currentLang = lang
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'
}

export function getLang(): 'zh' | 'en' {
  return currentLang
}

